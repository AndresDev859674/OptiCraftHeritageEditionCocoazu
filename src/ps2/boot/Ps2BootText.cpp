float textWidth(const char* text, float pixelScale)
{
    if (!text || text[0] == '\0' || pixelScale <= 0.0f)
        return 0.0f;

    const std::size_t length = std::strlen(text);
    return static_cast<float>(length * kGlyphAdvance - 1) * pixelScale;
}

void draw(float x, float y, int z,
          const char* text, float pixelScale,
          Ps2BootRenderer::Color color)
{
    if (!text || pixelScale <= 0.0f)
        return;

    for (const char* cursor = text; *cursor; ++cursor)
    {
        if (*cursor != ' ')
        {
            const unsigned char* glyph = glyphFor(*cursor);
            for (int row = 0; row < kGlyphHeight; ++row)
            {
                for (int column = 0; column < kGlyphWidth; ++column)
                {
                    if ((glyph[row] & (1u << (kGlyphWidth - 1 - column))) == 0)
                        continue;

                    const float x0 = x + static_cast<float>(column) * pixelScale;
                    const float y0 = y + static_cast<float>(row) * pixelScale;
                    Ps2BootRenderer::drawRect(x0, y0,
                                              x0 + pixelScale, y0 + pixelScale,
                                              z, color);
                }
            }
        }
        x += static_cast<float>(kGlyphAdvance) * pixelScale;
    }
}

void drawCentered(float centerX, float y, int z,
                  const char* text, float pixelScale,
                  Ps2BootRenderer::Color color)
{
    draw(centerX - textWidth(text, pixelScale) * 0.5f,
         y, z, text, pixelScale, color);
}

