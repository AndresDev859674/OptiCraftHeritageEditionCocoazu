constexpr Glyph kQuestion   = {0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04};
constexpr Glyph kSlash      = {0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10};

const unsigned char* glyphFor(char value)
{
    unsigned char code = static_cast<unsigned char>(value);
    if (code >= 'a' && code <= 'z')
        code = static_cast<unsigned char>(code - 'a' + 'A');

    if (code >= 'A' && code <= 'Z')
        return kLetters[code - 'A'];
    if (code >= '0' && code <= '9')
        return kDigits[code - '0'];

    switch (code)
    {
        case '\'': return kApostrophe;
        case ':': return kColon;
        case '-': return kDash;
        case '.': return kDot;
        case '/': return kSlash;
        default: return kQuestion;
    }
}

